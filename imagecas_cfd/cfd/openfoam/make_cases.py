def make_case(cid, twin, tag, h, model, root, variant='tube', transient=False, init_from='', pulse=False):
    transient = transient or pulse
    info = json.load(open(os.path.join(GEOM, str(cid), 'slices.json')))
    fr = {k: np.array(v) for k, v in info['frame'].items()}
    c, n, e1, e2 = fr['c'], fr['n'], fr['e1'], fr['e2']
    case = os.path.join(root, tag, f'{cid}_{twin}')
    stl_txt, V = read_stl_scaled(os.path.join(GEOM, str(cid), f'{twin}.stl' if variant == 'tube' else f'{twin}_{variant}.stl'))
    write(os.path.join(case, 'constant', 'triSurface', 'lumen.stl'), stl_txt)

    def world(d, u=0.0, v=0.0):          # mm frame coords -> world metres
        return (c - d * n + u * e1 + v * e2) * 1e-3

    sl = {round(s['depth_mm'], 2): s for s in info['slices']}
    # PW-Doppler sample volumes at the slice centroid (same centroid for both twins)
    probes_U, meta = [], []
    for d in ECHO_DEPTHS:
        s = sl[round(d, 2)]; cu, cv = s['real']['cu'], s['real']['cv']
        probes_U.append(world(d, cu, cv)); meta.append(dict(depth_mm=d, k=0))
        for j in range(6):
            a = j * np.pi / 3
            probes_U.append(world(d, cu + SV_R * np.cos(a), cv + SV_R * np.sin(a))); meta.append(dict(depth_mm=d, k=j + 1))
    # pressure probes: centroid of the deepest slice, 1 Deq into the inlet extension; and 2 Deq into the aorta
    sd, s0 = info['slices'][-1]['real'], info['slices'][0]['real']
    d_in = info['depth_mm'] + 1.0 * info['inlet_Deq_mm']
    d_out = info['start_mm'] - 2.0 * info['outlet_Deq_mm']
    probes_p = [world(d_in, sd['cu'], sd['cv']), world(d_out, s0['cu'], s0['cv'])]
    if variant.startswith('lv'):   # LV-cavity inflow: pressure probe deep in the LV cavity (see build_lv_twins.py)
        lvi = json.load(open(os.path.join(GEOM, str(cid), f'lv_info{variant[2:]}.json')))
        probes_p[0] = np.array(lvi['p_probe_lv_world_mm']) * 1e-3; d_in = float('nan')
    planes = [(f'd{str(d).replace(".", "p")}', world(d, sl[round(d, 2)]['real']['cu'], sl[round(d, 2)]['real']['cv']), n)
              for d in ECHO_DEPTHS]
    loc = world(7.0, sl[7.0]['real']['cu'], sl[7.0]['real']['cv']) + 1.234e-6

    bm, ncell = block_mesh(c, n, e1, e2, V, h)
    # LVOT refinement box: d from 16 mm (LV side) to -2 mm (aorta), +-30 mm across; local axes e1=n, e3=e2, e2=e3 x e1
    le2 = np.cross(e2, n)
    box_origin = (c - 16.0 * n - 30.0 * le2 - 30.0 * e2) * 1e-3
    write(os.path.join(case, 'system', 'blockMeshDict'), bm)
    write(os.path.join(case, 'system', 'snappyHexMeshDict'), snappy(loc, box_origin, np.array([18.0, 60.0, 60.0]) * 1e-3, n, e2, inlet_level=0 if variant.startswith('lv') else 1))
    write(os.path.join(case, 'system', 'controlDict'), control_dict(probes_U, probes_p, planes, transient, pulse))
    for name, txt in (('fvSchemes', FV_SCHEMES_TR if transient else FV_SCHEMES),
                      ('fvSolution', FV_SOLUTION_TR if transient else FV_SOLUTION), ('meshQualityDict', MESH_QUALITY),
                      ('surfaceFeatureExtractDict', FEATURE), ('decomposeParDict', DECOMP)):
        write(os.path.join(case, 'system', name), txt)
    write(os.path.join(case, 'constant', 'transportProperties'), TRANSPORT)
    write(os.path.join(case, 'constant', 'turbulenceProperties'), turbulence(model))
    for name, txt in zero_fields(model, info['inlet_Deq_mm'] * 1e-3, pulse).items():
        write(os.path.join(case, '0', name), txt)
    if init_from:   # reuse the mesh and the final steady U, p of an earlier run of the same geometry
        import glob, shutil
        src = os.path.join(root, init_from, f'{cid}_{twin}')
        assert os.path.exists(os.path.join(src, 'mesh.done')), src
        dst_mesh = os.path.join(case, 'constant', 'polyMesh')
        if os.path.exists(dst_mesh):
            shutil.rmtree(dst_mesh)
        shutil.copytree(os.path.join(src, 'constant', 'polyMesh'), dst_mesh)
        last = max((p for p in glob.glob(os.path.join(src, '[0-9]*')) if os.path.basename(p).replace('.', '', 1).isdigit() and os.path.basename(p) != '0'), key=lambda p: float(os.path.basename(p)))
        for fld in ('U', 'p') if not pulse else ():        # pulsatile runs start from rest: mesh only
            shutil.copy(os.path.join(last, fld), os.path.join(case, '0', fld))
        for f in ('mesh.done', 'log.checkMesh'):
            shutil.copy(os.path.join(src, f), os.path.join(case, f))
    write(os.path.join(case, 'Allrun'), ALLRUN_T.replace('APP', 'pimpleFoam' if transient else 'simpleFoam'), exe=True)
    json.dump(dict(id=cid, twin=twin, tag=tag, h_mm=h, model=model, Q_m3s=Q, nu=NU, echo_depths_mm=ECHO_DEPTHS,
                   sv_ring_mm=SV_R, probe_meta=meta, p_probe_depths_mm=[d_in, d_out], variant=variant, n=n.tolist(),
                   background_cells=ncell, transient=transient, t_end_s=T_END if transient else None,
                   t_avg_s=T_AVG if transient and not pulse else None, init_from=init_from,
                   pulse=dict(t_sys_s=T_SYS, t_peak_s=T_PEAK, q_peak_m3s=Q, sv_ml=Q * T_SYS / 2 * 1e6, gate_dt_s=GATE_DT) if pulse else None),
              open(os.path.join(case, 'case.json'), 'w'), indent=1)
    return case, ncell


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ids', default='')
    ap.add_argument('--twins', default='real,circle')
    ap.add_argument('--h', type=float, default=1.0, help='background cell size, mm (surface + LVOT region = h/2)')
    ap.add_argument('--model', default='laminar', help='laminar or kOmegaSST')
    ap.add_argument('--tag', default='')
    ap.add_argument('--variant', default='tube', help='tube (straight inlet extension), lv (LV-cavity inflow), lv_apical (apical inflow only) or lv_big (enlarged LV, --grow-to); lv* need build_lv_twins.py')
    ap.add_argument('--transient', action='store_true', help='pimpleFoam, constant Q, time-averaged from T_AVG')
    ap.add_argument('--init-from', default='', help='tag of a finished run of the same variant: reuse its mesh and final U, p (mesh only with --pulse)')
    ap.add_argument('--pulse', action='store_true', help='pimpleFoam, one systole from rest with a raised-cosine flow waveform (T_SYS, T_PEAK); needs echo_spectrum.py write --runtime')
    args = ap.parse_args()
    ids = [int(x) for x in args.ids.split(',')] if args.ids else \
        [int(r['id']) for r in csv.DictReader(open(os.path.join(CFD, 'case_selection.csv')))]
    tag = args.tag or f"{args.variant + '_' if args.variant != 'tube' else ''}{'lam' if args.model == 'laminar' else args.model}{'_pulse' if args.pulse else ('_tr' if args.transient else '')}_h{args.h:g}"
    root = os.path.join(CFD, 'runs')
    for cid in ids:
        for tw in args.twins.split(','):
            case, ncell = make_case(cid, tw, tag, args.h, args.model, root, args.variant, args.transient, args.init_from, args.pulse)
            print(f'{os.path.relpath(case, CFD)}  background cells {ncell}')


if __name__ == '__main__':
    main()
