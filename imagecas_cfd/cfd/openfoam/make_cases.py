def control_dict(probes_U, probes_p, planes, transient=False, pulse=False):
    pts_U = '\n'.join('            ' + vec(p) for p in probes_U)
    pts_p = '\n'.join('            ' + vec(p) for p in probes_p)
    surf = '\n'.join(f"""            {name}
            {{
                type cuttingPlane;
                planeType pointAndNormal;
                pointAndNormalDict {{ point {vec(p)}; normal {vec(nn)}; }}
                interpolate false;
            }}""" for name, p, nn in planes)
    if pulse:
        timing = f"""application     pimpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {T_SYS};
deltaT          1e-4;
adjustTimeStep  yes;
maxCo           {MAX_CO};
maxDeltaT       5e-4;
writeControl    adjustableRunTime;
writeInterval   0.0275;
purgeWrite      0;"""
        fields, pint = '(U p)', 1
        avg = '\n    // emulated PW gate volumes, sampled every GATE_DT (written by echo_spectrum.py write --runtime)\n    #include "echoGateFO"'
    elif transient:
        timing = f"""application     pimpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {T_END};
deltaT          1e-4;
adjustTimeStep  yes;
maxCo           {MAX_CO};
maxDeltaT       1e-3;
writeControl    adjustableRunTime;
writeInterval   0.05;
purgeWrite      2;"""
        fields = '(U p UMean)'
        avg = f"""
    // time-averaged velocity and its fluctuation (UPrime2Mean), from T_AVG on
    fieldAverage1
    {{
        type            fieldAverage;
        libs            (fieldFunctionObjects);
        writeControl    writeTime;
        timeStart       {T_AVG};
        fields
        (
            U {{ mean on; prime2Mean on; base time; }}
            p {{ mean on; prime2Mean off; base time; }}
        );
    }}"""
        pint = 1
    else:
        timing = f"""application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {END_ITER};
deltaT          1;
writeControl    timeStep;
writeInterval   {WRITE_EVERY};
purgeWrite      2;"""
        fields, avg, pint = '(U p)', '', 10
    return HDR.format(cls='dictionary', obj='controlDict') + f"""
{timing}
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{{avg}
    // PW-Doppler sample volumes: for each echo depth, the slice centroid + 6 points on a {SV_R} mm ring
    probesU
    {{
        type            probes;
        libs            (sampling);
        writeControl    timeStep;
        writeInterval   {pint};
        fields          (U);
        probeLocations
        (
{pts_U}
        );
    }}
    // pressure at the slice centroid in the inlet extension and in the aortic extension
    probesP
    {{
        type            probes;
        libs            (sampling);
        writeControl    timeStep;
        writeInterval   {pint};
        fields          (p);
        probeLocations
        (
{pts_p}
        );
    }}
    // velocity on the echo planes (for figures), written with each time directory
    echoPlanes
    {{
        type            surfaces;
        libs            (sampling);
        writeControl    writeTime;
        surfaceFormat   raw;
        fields          {fields};
        interpolationScheme cellPoint;
        surfaces
        {{
{surf}
        }}
    }}
}}
"""


