"""Generate OpenFOAM (ESI/OpenCFD v2512) cases for the LVOT patient twins.

One case per (id, twin): runs/<tag>/<id>_<twin>/
  constant/triSurface/lumen.stl   twin STL scaled mm -> m (solids inlet/outlet/wall kept)
  system/blockMeshDict            background box aligned with the LVOT frame (n, e1, e2)
  system/snappyHexMeshDict        surface refinement + LVOT-region refinement + wall layers
  system/controlDict              simpleFoam + probes at the echo sample volumes + pressure probes
  0/                              U, p (+ k, omega, nut for k-omega SST)
  Allrun                          mesh, solve (parallel), reconstruct latest time

Geometry: a point at depth d (mm below the valve plane) is c - d*n + u*e1 + v*e2.
Flow goes from inlet (LV, large d) to outlet (aorta, negative d), i.e. along +n.

Run from the imagecas folder (needs only numpy):
  uv run --python 3.12 --with numpy python -I cfd/openfoam/make_cases.py            # all 24, laminar, h=1.0
  uv run --python 3.12 --with numpy python -I cfd/openfoam/make_cases.py --ids 388 --twins real --h 0.7 --tag lam_h0.7
  uv run --python 3.12 --with numpy python -I cfd/openfoam/make_cases.py --ids 388,142 --model kOmegaSST --tag sst_h1.0
Transient (pimpleFoam, constant Q), reusing the mesh and final steady fields of an existing steady run:
  uv run --python 3.12 --with numpy python -I cfd/openfoam/make_cases.py --ids 388 --variant lv_apical --transient --init-from lv_apical_lam_h1
"""
import argparse, csv, json, os, stat
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
CFD = os.path.dirname(HERE)
GEOM = os.path.join(CFD, 'geometry')

Q = 4.0e-4            # m^3/s  (400 mL/s, typical peak-systolic LVOT flow), same for every twin
NU = 3.5e-6           # m^2/s  blood, Newtonian
ECHO_DEPTHS = (5.0, 7.5, 10.0)
SV_R = 1.5            # mm, radius of the PW-Doppler sample-volume ring (centre + 6 points)
NPROC = 4
END_ITER = 2000
WRITE_EVERY = 500
# transient (pimpleFoam) settings: constant peak flow, started from the final steady fields
T_END = 0.5           # s of physical time; constant Q started from the final steady fields
T_AVG = 0.2           # s, start of time-averaging (fieldAverage + probe statistics)
MAX_CO = 0.8
# pulsatile (one systole from rest): raised-cosine rise to Q at T_PEAK, raised-cosine fall to 0 at T_SYS -> SV = Q*T_SYS/2
T_SYS = 0.33          # s, ejection time
T_PEAK = 0.11         # s, time of peak flow (early peak, as in normal ejection)
PULSE_DT = 0.0025     # s, table resolution
GATE_DT = 0.001       # s, interval for the emulated PW-gate samples (echoGateFO, written by echo_spectrum.py)


def pulse_q(t):
    t = np.asarray(t, float)
    up = Q * 0.5 * (1 - np.cos(np.pi * np.clip(t, 0, T_PEAK) / T_PEAK))
    dn = Q * 0.5 * (1 + np.cos(np.pi * np.clip(t - T_PEAK, 0, T_SYS - T_PEAK) / (T_SYS - T_PEAK)))
    return np.where(t <= T_PEAK, up, np.where(t <= T_SYS, dn, 0.0))


def pulse_table():
    t = np.round(np.arange(0, T_SYS + PULSE_DT / 2, PULSE_DT), 6)
    return 'table (' + ' '.join('(%g %.6g)' % (a, b) for a, b in zip(t, pulse_q(t))) + ')'
HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  generated by cfd/openfoam/make_cases.py
\\*---------------------------------------------------------------------------*/
FoamFile {{ version 2.0; format ascii; class {cls}; object {obj}; }}
"""


def vec(p):
    return '(%.9g %.9g %.9g)' % tuple(p)


def read_stl_scaled(src, s=1e-3):
    out, verts = [], []
    with open(src) as fh:
        for line in fh:
            t = line.strip()
            if t.startswith('vertex'):
                x = np.array(t.split()[1:4], float)
                verts.append(x)
                out.append('   vertex %.9e %.9e %.9e\n' % tuple(x * s))
            else:
                out.append(line)
    return ''.join(out), np.array(verts)


def write(path, text, exe=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)
    if exe:
        os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def block_mesh(c, n, e1, e2, V, h):
    """Box in frame coords (s along n, u along e1, v along e2) enclosing the STL, in metres."""
    rel = V - c
    s, u, v = rel @ n, rel @ e1, rel @ e2
    m = 3 * h
    lo = np.array([s.min() - m, u.min() - m, v.min() - m]); hi = np.array([s.max() + m, u.max() + m, v.max() + m])
    ax = [n, e1, e2]
    if np.linalg.det(np.array(ax)) < 0:          # keep the hex right-handed
        ax = [n, e2, e1]; lo[[1, 2]] = lo[[2, 1]]; hi[[1, 2]] = hi[[2, 1]]
    def P(a, b, cc):
        return (c + a * ax[0] + b * ax[1] + cc * ax[2]) * 1e-3
    corners = [P(lo[0], lo[1], lo[2]), P(hi[0], lo[1], lo[2]), P(hi[0], hi[1], lo[2]), P(lo[0], hi[1], lo[2]),
               P(lo[0], lo[1], hi[2]), P(hi[0], lo[1], hi[2]), P(hi[0], hi[1], hi[2]), P(lo[0], hi[1], hi[2])]
    N = np.ceil((hi - lo) / h).astype(int)
    return HDR.format(cls='dictionary', obj='blockMeshDict') + f"""
scale 1;
vertices
(
{chr(10).join('    ' + vec(p) for p in corners)}
);
blocks ( hex (0 1 2 3 4 5 6 7) ({N[0]} {N[1]} {N[2]}) simpleGrading (1 1 1) );
edges ();
boundary ( background {{ type patch; faces ( (0 3 2 1) (4 5 6 7) (0 1 5 4) (2 3 7 6) (0 4 7 3) (1 2 6 5) ); }} );
""", int(N.prod())


